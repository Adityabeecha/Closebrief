-- v1.3: dataset scoping. Every metric/KPI belongs to a dataset; the dashboard
-- shows only the active dataset. Existing rows are backfilled into one
-- "Legacy import" dataset so nothing is orphaned.

CREATE TABLE IF NOT EXISTS datasets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    source_upload_id TEXT,
    is_active INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE metrics ADD COLUMN IF NOT EXISTS dataset_id BIGINT REFERENCES datasets(id);
ALTER TABLE kpi_configs ADD COLUMN IF NOT EXISTS dataset_id BIGINT REFERENCES datasets(id);

-- Backfill: one legacy dataset owns all pre-existing metrics/kpi_configs.
DO $$
DECLARE legacy_id BIGINT;
BEGIN
    IF EXISTS (SELECT 1 FROM metrics WHERE dataset_id IS NULL)
       OR EXISTS (SELECT 1 FROM kpi_configs WHERE dataset_id IS NULL) THEN
        INSERT INTO datasets (name, is_active) VALUES ('Legacy import', 1)
        RETURNING id INTO legacy_id;
        UPDATE metrics SET dataset_id = legacy_id WHERE dataset_id IS NULL;
        UPDATE kpi_configs SET dataset_id = legacy_id WHERE dataset_id IS NULL;
    END IF;
END $$;

-- Swap the old global-unique constraints for dataset-scoped ones.
ALTER TABLE metrics DROP CONSTRAINT IF EXISTS metrics_name_key;
ALTER TABLE kpi_configs DROP CONSTRAINT IF EXISTS kpi_configs_source_metric_key;
CREATE UNIQUE INDEX IF NOT EXISTS metrics_dataset_name_key ON metrics(dataset_id, name);
CREATE UNIQUE INDEX IF NOT EXISTS kpi_configs_dataset_metric_key ON kpi_configs(dataset_id, source_metric);
