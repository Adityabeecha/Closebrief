"""SQLite→Postgres SQL translation (the layer that lets one query string run on
both backends). Guards the recurring cross-DB bug class."""

import pytest
from dbharness import TEST_DATABASE_URL, use_test_db

from app import db
from app.db import _translate


def test_placeholders_and_percent():
    assert _translate("SELECT * FROM t WHERE a = ?") == "SELECT * FROM t WHERE a = %s"
    # SQL literal contents are untouched by dialect translation.
    assert _translate("WHERE p NOT LIKE '%-digest'") == "WHERE p NOT LIKE '%-digest'"


def test_percent_not_escaped_without_params():
    # No params -> psycopg sends the string verbatim (no %% collapse), so a
    # literal % must be left alone or the value would be corrupted to %%.
    assert _translate("WHERE name = 'GM %'", has_params=False) == "WHERE name = 'GM %'"
    assert _translate("WHERE name = 'GM %'", has_params=True) == "WHERE name = 'GM %'"


def test_null_safe_is_becomes_distinct_from():
    # SQLite's `col IS ?` is null-safe equality; Postgres needs IS NOT DISTINCT FROM.
    assert _translate("WHERE workspace_id IS ?") == "WHERE workspace_id IS NOT DISTINCT FROM %s"
    assert _translate("WHERE a IS NOT ?") == "WHERE a IS DISTINCT FROM %s"
    # A normal IS NULL is untouched.
    assert _translate("WHERE a IS NULL") == "WHERE a IS NULL"


def test_insert_or_ignore_becomes_on_conflict():
    out = _translate("INSERT OR IGNORE INTO t (a) VALUES (?)")
    assert out.startswith("INSERT INTO t") and out.endswith("ON CONFLICT DO NOTHING")


@pytest.mark.parametrize("has_params", [False, True])
@pytest.mark.parametrize("literal", ["'?'",
                                   "'it''s ? with 10% and IS ?'",
                                   "'INSERT OR IGNORE INTO x IS NOT ?'",
                                   "'%x%'"])
def test_single_quoted_literals_are_preserved(literal, has_params):
    assert _translate(f"SELECT {literal}, ?", has_params=has_params) == f"SELECT {literal}, %s"


def test_only_unquoted_null_safe_comparisons_change():
    sql = "SELECT 'x IS ? and y IS NOT ?', a IS ?, b IS NOT ?"
    assert _translate(sql) == "SELECT 'x IS ? and y IS NOT ?', a IS NOT DISTINCT FROM %s, b IS DISTINCT FROM %s"


def test_percent_operator_outside_literal_is_driver_escaped_only_with_params():
    assert _translate("SELECT 10 % 3, '%x%', ?", True) == "SELECT 10 %% 3, '%x%', %s"
    assert _translate("SELECT 10 % 3, '%x%'", False) == "SELECT 10 % 3, '%x%'"


def test_insert_or_ignore_keeps_quoted_question_mark():
    assert _translate("INSERT OR IGNORE INTO t (a,b) VALUES ('?', ?);") == (
        "INSERT INTO t (a,b) VALUES ('?', %s) ON CONFLICT DO NOTHING")


