@pytest.mark.skipif(not TEST_DATABASE_URL, reason="requires TEST_DATABASE_URL (Postgres only)")
def test_driver_preserves_literal_question_marks_percents_and_escaped_quotes(postgres_db):
    row = postgres_db.execute(
        "SELECT 'it''s ? and 10% and %s' AS literal, ? LIKE '%x%' AS matches, 10 % 3 AS remainder", ("xxx",)
    ).fetchone()
    assert row == {"literal": "it's ? and 10% and %s", "matches": True, "remainder": 1}
    assert postgres_db.execute("SELECT 'GM % ?' AS literal").fetchone()["literal"] == "GM % ?"


@pytest.mark.skipif(not TEST_DATABASE_URL, reason="requires TEST_DATABASE_URL (Postgres only)")
def test_every_integer_id_from_migrated_schema_supports_lastrowid(postgres_db):
    tables = postgres_db._raw.execute("""
        SELECT c.relname
        FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid
        JOIN pg_namespace n ON n.oid=c.relnamespace
        WHERE n.nspname='public' AND c.relkind='r' AND a.attname='id'
          AND a.atttypid IN ('smallint'::regtype, 'integer'::regtype, 'bigint'::regtype)
    """).fetchall()
    assert tables
    assert all(postgres_db._has_generated_id(row["relname"]) for row in tables)
    # A newly introduced table must work without adding any Python table name.
    postgres_db.execute("CREATE TABLE identity_probe (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value TEXT)")
    try:
        cursor = postgres_db.execute("INSERT INTO identity_probe(value) VALUES (?)", ("RETURNING? 10%",))
        assert cursor.lastrowid == 1
        literal_cursor = postgres_db.execute("INSERT INTO identity_probe(value) VALUES ('RETURNING ? 10%')")
        assert literal_cursor.lastrowid == 2
        assert postgres_db.execute("SELECT value FROM identity_probe WHERE id=1").fetchone()["value"] == "RETURNING? 10%"
    finally:
        postgres_db.execute("DROP TABLE identity_probe")
        postgres_db.commit()


def test_generated_id_lookup_is_cached_for_tables_without_one(monkeypatch):
    # Inserts into an id-less table (every metric_values row of an import) must
    # not pay a catalogue round trip each time; migrate() is what resets it.
    import app.db as db

    class Raw:
        def __init__(self):
            self.catalogue = 0

        def execute(self, sql, params=None):
            raw = self

            class Cur:
                def fetchone(self):
                    if "to_regclass" in sql:
                        raw.catalogue += 1
                        return {"present": True, "generated": False}
                    return None
            return Cur()

    monkeypatch.setattr(db, "_GENERATED_ID_CACHE", {})
    raw = Raw()
    conn = db.PostgresConnection.__new__(db.PostgresConnection)
    conn._raw = raw
    for _ in range(3):
        assert conn._has_generated_id("metric_values") is False
    assert raw.catalogue == 1
    db._GENERATED_ID_CACHE.clear()
    assert conn._has_generated_id("metric_values") is False and raw.catalogue == 2
